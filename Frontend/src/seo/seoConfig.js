/**
 * Returns the SEO metadata ({ title, description }) for a given pathname
 */
export function getSeoForPath(pathname) {
  if (!pathname) return DEFAULT_SEO;

  // Exact match
  if (pageSeoMap[pathname]) {
    return pageSeoMap[pathname];
  }

  // Check prefix routes
  if (pathname.startsWith("/gallery/events/")) {
    return {
      title: "NSCET | Event Gallery",
      description: "Explore events, workshops, and celebrations at NSCET."
    };
  }

  return DEFAULT_SEO;
}

/**
 * Dynamically updates the <meta name="description"> tag in document head
 */
export function updateMetaDescription(description) {
  if (!description) return;
  let metaTag = document.querySelector('meta[name="description"]');
  if (!metaTag) {
    metaTag = document.createElement("meta");
    metaTag.setAttribute("name", "description");
    document.head.appendChild(metaTag);
  }
  metaTag.setAttribute("content", description);
}
